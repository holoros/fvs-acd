#!/usr/bin/env python3
"""Build docs/preregistrations.md from the 14.2 refinement record in scripts/v14.2dev/.

Run from the repository root: python3 scripts/tools/build_prereg_index.py
Lists every pre-registration, draft and RESULT markdown file by number, with its first heading.
Files whose name contains PREV are skipped. No em dashes."""
import glob, os, re

ROOT = "scripts/v14.2dev"
OUT = "docs/preregistrations.md"
KIND = {"plan": "plan", "draft": "draft (not registered)", "result": "result"}

rows = {}
for p in sorted(glob.glob(ROOT + "/**/*.md", recursive=True)):
    b = os.path.basename(p)
    if "PREV" in b:
        continue
    m = re.search(r"PREREG(\d+b?)", b) or re.search(r"prereg(\d+b?)", p)
    if not m:
        continue
    kind = "result" if "RESULT" in b else "draft" if "DRAFT" in b else "plan" if "PREREG" in b else None
    if kind is None:
        continue
    with open(p, encoding="utf-8") as f:
        head = next((l.strip("# \n") for l in f if l.startswith("#")), b)
    rows.setdefault(m.group(1), []).append((kind, p, head))

def key(n):
    return (int(re.match(r"\d+", n).group()), n)

lines = [
    "# Pre-registration index",
    "",
    "Every pre-registration, unregistered draft and RESULT in `scripts/v14.2dev/`, by number, with",
    "the first heading of each file. Generated by `scripts/tools/build_prereg_index.py`; rerun it after",
    "adding a study rather than editing this file by hand. The registration record for each study",
    "(md5 and time) is the `prereg_md5.txt` or `logs/` file beside its plan. The 14.1 gate",
    "pre-registrations (PREREG2 revision 5, and pre-registrations 3 and 4 of September 25 and 26, 2026)",
    "are described in `VERSION_HISTORY.md` Era 8; PREREG2 revision 5 is in `docs/v14.1/` on branch",
    "`engines-14.1-20260924`. 14.3 pre-registrations, when they exist, are in `docs/v14.3/`.",
    "",
    "| No. | Kind | Title | File |",
    "|:--|:--|:--|:--|",
]
for n in sorted(rows, key=key):
    for kind, p, head in sorted(rows[n], key=lambda r: (["plan", "draft", "result"].index(r[0]), r[1])):
        lines.append(f"| {n} | {KIND[kind]} | {head.replace('|', '/')} | `{p}` |")
open(OUT, "w", encoding="utf-8").write("\n".join(lines) + "\n")
print(f"wrote {OUT}: {sum(len(v) for v in rows.values())} files, {len(rows)} studies")
