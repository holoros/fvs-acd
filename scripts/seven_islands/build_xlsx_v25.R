suppressMessages(library(openxlsx))
setwd("~/silc_cfi")
sc   <- read.csv("silc_cfi_value_v25_scorecard.csv")
cov  <- read.csv("silc_cfi_v25_coverage_by_model.csv")
spp  <- read.csv("silc_cfi_obs_species_split_v25.csv")
spec <- read.csv("silc_merch_specs.csv")
byp  <- read.csv("silc_cfi_value_v25_byplot.csv")
eq   <- read.csv("equivalence_test_results_v25.csv")
stress <- read.csv("v25_stress_coverage_check.csv")
bak1211 <- read.csv("bakuzis_v1211_full_v25_relations.csv")
bak131  <- read.csv("bakuzis_v131_full_v25_relations.csv")

wb <- createWorkbook()
hdr <- createStyle(textDecoration="bold", halign="center", valign="center", border="TopBottom")
ctr <- createStyle(halign="center", valign="center")

addSheet <- function(nm, df) {
  addWorksheet(wb, nm)
  writeData(wb, nm, df, headerStyle=hdr)
  addStyle(wb, nm, ctr, rows=2:(nrow(df)+1), cols=1:ncol(df), gridExpand=TRUE)
  setColWidths(wb, nm, cols=1:ncol(df), widths="auto")
  freezePane(wb, nm, firstRow=TRUE)
}
addSheet("Scorecard_v25", sc)
addSheet("Coverage_v25", cov)
addSheet("ObsSpeciesSplit_v25", spp)
addSheet("MerchSpec_SILC", spec)
addSheet("ByPlot_v25", byp)
addSheet("EquivalenceTests_v25", eq)
addSheet("PlotCoverage_137ceiling_v25", stress)
addSheet("Bakuzis_v1211full_v25", bak1211)
addSheet("Bakuzis_v131full_v25", bak131)

saveWorkbook(wb, "v25_docbuild/SILC_Benchmark_DataTables_v25.xlsx", overwrite=TRUE)
cat("wrote SILC_Benchmark_DataTables_v25.xlsx\n")
